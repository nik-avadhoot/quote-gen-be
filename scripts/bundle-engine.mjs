#!/usr/bin/env node
// S7-R: bundle the governed costing engine into the calculate-batch-row Edge
// Function, byte for byte, and record exactly what was bundled.
//
//   node scripts/bundle-engine.mjs          copy the engine and write _engine/manifest.js
//   node scripts/bundle-engine.mjs --check  CP-108: fail unless the bundled copy, the
//                                           manifest and the frontend source all agree,
//                                           and the copied import closure is complete
//
// WHY A COPY AND NOT A SECOND IMPLEMENTATION. The Edge runtime cannot import from
// the frontend repository, so the engine has to travel with the function. It
// travels UNCHANGED - no transpile, no minify, no edit - so the copy is the same
// bytes the `test:costing` golden gate runs against. This script proves that on
// every run rather than leaving it to be assumed.
//
// THE ENGINE VERSION IS DERIVED FROM THE BYTES. `engine_version` is the governed
// Calculation Defaults value the database binds into every qca/1 attestation. The
// executor refuses to sign unless the Release's engine_version equals the label
// written here, and the label is a digest of the bundled files - so a Release can
// never name an engine the executor is not actually running.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const FE_SRC = resolve(here, '../../quote-gen-fe/src');
const OUT = resolve(here, '../supabase/functions/calculate-batch-row/_engine');

// The complete import closure of src/engine/costing.js. Rate Master modules and
// editable rate defaults are intentionally outside this closure: Calculate
// receives already-established effective material rates.
const FILES = [
  'engine/costing.js',
  'engine/costingTables.js',
  'engine/calcDefaults.js',
  'engine/resolveAuthority.js',
  'engine/interestBasis.js',
];

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const posix = (p) => p.split('\\').join('/');

function sourceManifest() {
  const files = FILES.map((path) => ({ path, sha256: sha256(readFileSync(join(FE_SRC, path))) }));
  const digest = sha256(files.map((f) => `${f.path} ${f.sha256}`).join('\n'));
  return { files, digest, engine_version: `engine/qe1-${digest.slice(0, 16)}` };
}

function closureProblems(root) {
  const problems = [];
  const importRe = /^\s*(?:import|export)\s[^'"]*?from\s*['"]([^'"]+)['"]/gm;
  for (const path of FILES) {
    const text = readFileSync(join(root, path), 'utf8');
    for (const m of text.matchAll(importRe)) {
      const spec = m[1];
      if (!spec.startsWith('.')) { problems.push(`${path}: non-relative import '${spec}'`); continue; }
      const target = posix(relative(root, resolve(dirname(join(root, path)), spec)));
      if (!FILES.includes(target)) problems.push(`${path}: imports '${target}', which is not bundled`);
    }
  }
  return problems;
}

function manifestModule(m) {
  return '// GENERATED by scripts/bundle-engine.mjs - do not edit by hand.\n'
    + `export const MANIFEST = ${JSON.stringify(m, null, 2)};\n`;
}

async function check() {
  const failures = [];
  const expected = sourceManifest();
  failures.push(...closureProblems(FE_SRC));
  for (const path of ['engine/costing.js','engine/calcDefaults.js','engine/resolveAuthority.js']) {
    const source = readFileSync(join(FE_SRC, path), 'utf8');
    if (/supplier.?credit|CREDIT_PCT|interest_pct|creditCostPct/.test(source))
      failures.push(`${path}: supplier-credit authority leaked into the Batch engine`);
  }
  for (const f of expected.files) {
    const copy = join(OUT, f.path);
    if (!existsSync(copy)) { failures.push(`missing bundled file ${f.path}`); continue; }
    const got = sha256(readFileSync(copy));
    if (got !== f.sha256) failures.push(`${f.path}: bundled ${got.slice(0, 12)} != source ${f.sha256.slice(0, 12)}`);
  }
  const manifestPath = join(OUT, 'manifest.js');
  if (!existsSync(manifestPath)) {
    failures.push('missing _engine/manifest.js');
  } else {
    const { MANIFEST } = await import(pathToFileURL(manifestPath).href);
    if (JSON.stringify(MANIFEST) !== JSON.stringify(expected)) failures.push('manifest does not match the source');
  }
  if (failures.length) {
    for (const f of failures) console.log(`not ok  ${f}`);
    console.log(`\nCP-108 FAILED - the Edge Function would not be running the governed engine`);
    process.exit(1);
  }
  console.log(`ok    ${expected.files.length} engine files byte-identical to quote-gen-fe/src`);
  console.log('ok    import closure complete - nothing the engine imports is missing from the bundle');
  console.log(`ok    manifest matches the source; engine_version ${expected.engine_version}`);
  console.log('\nCP-108 engine-bundle fidelity: pass');
}

function write() {
  const problems = closureProblems(FE_SRC);
  if (problems.length) {
    for (const p of problems) console.error(p);
    process.exit(1);
  }
  for (const path of FILES) {
    mkdirSync(dirname(join(OUT, path)), { recursive: true });
    copyFileSync(join(FE_SRC, path), join(OUT, path));
  }
  // Node needs the copied .js files treated as ES modules; Deno ignores this.
  writeFileSync(join(OUT, 'package.json'), '{ "type": "module" }\n');
  const m = sourceManifest();
  writeFileSync(join(OUT, 'manifest.js'), manifestModule(m));
  console.log(`bundled ${FILES.length} files; engine_version ${m.engine_version}`);
}

if (process.argv.includes('--check')) await check(); else write();
